/**
 * Service to fetch live train data. Returns known trains or generic fallback.
 */
export async function getLiveTrainData(trainNumber: string): Promise<LiveTrainData> {
  const train = MOCK_TRAIN_DATABASE[trainNumber];
  if (train) {
    const coachComp = train.coachComposition ?? MOCK_COACH_DATABASE[trainNumber] ?? {
      trainNumber,
      available: false,
      totalCoaches: 0,
      coaches: [],
      updatedAt: new Date().toISOString(),
    };
    // Return a copy with fresh timestamp and coach composition
    return {
      ...train,
      coachComposition: coachComp,
      lastUpdatedTime: new Date().toISOString(),
    };
  }

  return generateGenericMockTrain(trainNumber);
}

